# The annotated paper as pages of the site: each section of docs/paper, in
# both languages, into site/docs/paper/ with the suffix layout
# mkdocs-static-i18n reads. The acotaciones become `.nota` blocks (Markdown in
# HTML), the title page loses its print-only blocks, and the figures are
# copied beside the pages.
#
#   python3 docs/paper/site.py [out-dir]
import pathlib, re, shutil, sys

here = pathlib.Path(__file__).resolve().parent
out = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else here.parent.parent / "site" / "docs" / "paper"
SECTIONS = ["00-front", "01-introduction", "02-engine", "03-conversion", "04-transfer", "05-animation",
            "06-lod", "07-compression-player", "08-evaluation", "09-limitations", "10-references"]
LABEL = {"en": "Note", "es": "Acotación"}


def convert(src, lang):
    # Track which fenced div a closing ::: belongs to, so only acotaciones emit </div>.
    stack, out_lines = [], []
    for line in src.splitlines():
        t = line.strip()
        if t == "::: {.nota}":
            stack.append("nota")
            out_lines += [f'<div class="nota" markdown data-label="{LABEL[lang]}">', ""]
        elif t in ("::: {#front}", "::: {#contents}"):
            stack.append("drop")
        elif t.startswith("## Contents") or t.startswith("## Índice"):
            continue
        elif t == ":::" and stack:
            if stack.pop() == "nota":
                out_lines += ["", "</div>"]
        else:
            out_lines.append(line)
    s = "\n".join(out_lines) + "\n"
    s = re.sub(r"(?<=\S) --(?= |$)", " –", s, flags=re.M)
    s = re.sub(r"(?:(?<= )|^)-- (?=\S)", "– ", s, flags=re.M)
    s = s.replace("{.unnumbered .unlisted .paper-title}", "").replace("{.unnumbered .unlisted}", "")
    s = s.replace("{.unnumbered}", "")
    return s


out.mkdir(parents=True, exist_ok=True)
for name in SECTIONS:
    for lang, suffix in (("en", ""), ("es", ".es")):
        src = (here / f"{name}{suffix}.md").read_text()
        src = re.sub(r"^<!--.*?-->\n", "", src, flags=re.S)
        (out / f"{name}{suffix}.md").write_text(
            "<!-- Copyright (c) 2026 jesus luque. -->\n<!-- Generated by docs/paper/site.py from docs/paper; edit the sources there. -->\n\n" + convert(src, lang))
if (out / "figures").exists():
    shutil.rmtree(out / "figures")
shutil.copytree(here / "figures", out / "figures")
print(out)
